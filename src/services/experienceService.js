import { API_BASE_URL } from '../config.js';
import { ApiError, apiRequest, apiUpload } from './apiClient.js';

/**
 * Experience data model (as stored by the server):
 * {
 *   id, name, description, status: 'draft' | 'published',
 *   brand:     { name, accentColor, logoUrl, coverUrl },   // coverUrl: optional splash hero image
 *   target:    { imageUrl, mindUrl, width, height, quality, featureCount },
 *   content:   { type: 'video' | 'image' | 'model', url, fileName, fit, loop, startMuted, playAnimations, aspect },
 *   placement: { scale, offsetX, offsetY, offsetZ, rotationX, rotationY, rotationZ },
 *   hotspots:  [{ id, label, x, y, z }], // x/y normalised from the target's top-left; z = height in target widths
 *   createdAt, updatedAt
 * }
 */

export const CONTENT_TYPES = [
  { value: 'video', label: 'Video', accept: '.mp4,.webm,.mov,.m4v,video/mp4,video/webm,video/quicktime' },
  { value: 'image', label: 'Image', accept: '.jpg,.jpeg,.png,.webp,image/jpeg,image/png,image/webp' },
  { value: 'model', label: '3D model', accept: '.glb,.gltf' },
];

export const DEFAULT_PLACEMENT = Object.freeze({
  scale: 1,
  offsetX: 0,
  offsetY: 0,
  offsetZ: 0,
  rotationX: 0,
  rotationY: 0,
  rotationZ: 0,
});

export function createEmptyDraft() {
  return {
    name: '',
    description: '',
    status: 'published',
    brand: { name: '', accentColor: '#e5173f', logoUrl: null, coverUrl: null, removeLogo: false, removeCover: false },
    target: { imageUrl: null, mindUrl: null, width: 0, height: 0, quality: null, featureCount: 0 },
    content: {
      type: 'video',
      url: null,
      fileName: null,
      fit: 'target',
      loop: true,
      startMuted: true,
      playAnimations: true,
      alignToTarget: false,
      aspect: 1,
    },
    placement: { ...DEFAULT_PLACEMENT },
    hotspots: [],
  };
}

/* ---------------------------------------------------------------------------
 * Data source. With the Node server running, everything goes through /api.
 * On a static host (e.g. Vercel) there is no API: published experiences are
 * read from /static-data (generated by `npm run export:static`) and the
 * admin becomes read-only.
 * ------------------------------------------------------------------------- */
let sourcePromise = null;

/** @returns {Promise<'api'|'static'>} */
export function getDataSource() {
  // eslint-disable-next-line no-undef
  if (__STATIC_HOST__) return Promise.resolve('static');
  if (!sourcePromise) {
    sourcePromise = fetch(`${API_BASE_URL}/api/health`)
      .then((r) => (r.ok && (r.headers.get('Content-Type') || '').includes('json') ? 'api' : 'static'))
      .catch(() => 'static');
  }
  return sourcePromise;
}

const STATIC_ROOT = '/static-data';
const READ_ONLY_MESSAGE =
  'This deployment is read-only (static hosting). Run the Node server (npm start) to create or edit experiences.';

async function staticJson(path, notFoundMessage) {
  let res;
  try {
    res = await fetch(`${STATIC_ROOT}${path}`, { cache: 'no-cache' });
  } catch {
    throw new ApiError(0, 'Network error: the experience data could not be loaded.');
  }
  if (!res.ok || !(res.headers.get('Content-Type') || '').includes('json')) {
    throw new ApiError(404, notFoundMessage);
  }
  return res.json();
}

const NOT_FOUND = 'This experience does not exist or is not published.';
const readOnly = () => Promise.reject(new ApiError(0, READ_ONLY_MESSAGE));

export async function listExperiences(opts) {
  if ((await getDataSource()) === 'api') return apiRequest('/api/experiences', opts);
  return staticJson('/index.json', 'No published experiences found.').catch((err) => {
    if (err.status === 404) return [];
    throw err;
  });
}

export async function getExperience(id, opts) {
  if ((await getDataSource()) === 'api') return apiRequest(`/api/experiences/${encodeURIComponent(id)}`, opts);
  return staticJson(`/experiences/${encodeURIComponent(id)}.json`, 'Experience not found.');
}

export async function getPublicExperience(id, opts) {
  if ((await getDataSource()) === 'api') {
    return apiRequest(`/api/public/experiences/${encodeURIComponent(id)}`, { ...opts, auth: false });
  }
  return staticJson(`/experiences/${encodeURIComponent(id)}.json`, NOT_FOUND);
}

export async function getHealth() {
  if ((await getDataSource()) === 'api') return apiRequest('/api/health', { auth: false });
  return { ok: true, adminAuth: 'static' };
}

export const checkAdminAuth = () => apiRequest('/api/auth/check');

export async function setExperienceStatus(id, status) {
  if ((await getDataSource()) === 'static') return readOnly();
  return apiRequest(`/api/experiences/${encodeURIComponent(id)}/status`, { method: 'PATCH', json: { status } });
}

export async function deleteExperience(id) {
  if ((await getDataSource()) === 'static') return readOnly();
  return apiRequest(`/api/experiences/${encodeURIComponent(id)}`, { method: 'DELETE' });
}

function buildFormData(draft, files) {
  const fd = new FormData();
  fd.append('data', JSON.stringify(draft));
  if (files.targetImage) fd.append('targetImage', files.targetImage);
  if (files.targetMind) fd.append('targetMind', files.targetMind, 'target.mind');
  if (files.content) fd.append('content', files.content);
  if (files.logo) fd.append('logo', files.logo);
  if (files.cover) fd.append('cover', files.cover);
  return fd;
}

/**
 * @param {object} draft Experience fields (see data model).
 * @param {{targetImage?: File, targetMind?: Blob, content?: File, logo?: File, cover?: File}} files
 */
export async function createExperience(draft, files, onProgress) {
  if ((await getDataSource()) === 'static') return readOnly();
  return apiUpload('/api/experiences', { formData: buildFormData(draft, files), onProgress });
}

export async function updateExperience(id, draft, files, onProgress) {
  if ((await getDataSource()) === 'static') return readOnly();
  return apiUpload(`/api/experiences/${encodeURIComponent(id)}`, {
    method: 'PUT',
    formData: buildFormData(draft, files),
    onProgress,
  });
}
